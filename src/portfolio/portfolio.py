"""
[PURPOSE]: Core Portfolio orchestrator managing Account, Positions, PnL, Margin, and state transitions upon Fills.
[DEPENDENCIES]: datetime, typing, src.execution.order, src.execution.fill, src.portfolio.account, src.portfolio.position, src.portfolio.pnl, src.portfolio.margin, src.portfolio.portfolio_state, src.portfolio.exceptions.
"""

from datetime import datetime, timezone
from typing import Dict, Any, Optional, Set
from src.execution.order import OrderSide
from src.execution.fill import Fill
from src.portfolio.account import Account
from src.portfolio.position import Position, PositionSide
from src.portfolio.pnl import calculate_realized_pnl, calculate_unrealized_pnl
from src.portfolio.margin import MarginModel, SimpleMarginModel
from src.portfolio.portfolio_state import PortfolioState
from src.portfolio.exceptions import PortfolioException

class Portfolio:
    """
    [PURPOSE]: Orchestration class managing portfolio accounting, position state machine, and equity tracking.
    [DEPENDENCIES]: Account, Position, PositionSide, Fill, PortfolioState, MarginModel.
    """
    def __init__(
        self,
        initial_capital: float = 10000.0,
        leverage: float = 5.0,
        margin_model: Optional[MarginModel] = None
    ):
        """
        [ARGS]:
            initial_capital — Account starting capital (> 0).
            leverage — Account position leverage.
            margin_model — Optional MarginModel strategy.
        """
        self.initial_capital = initial_capital
        self.account = Account(initial_capital=initial_capital, balance=initial_capital)
        self.positions: Dict[str, Position] = {}
        self.processed_fill_ids: Set[str] = set()
        self.leverage = leverage
        self.margin_model = margin_model or SimpleMarginModel()
        self.last_timestamp: Optional[datetime] = None

    def apply_fill(self, fill: Fill) -> PortfolioState:
        """
        [PURPOSE]: Apply trade Fill, update Position state (Open, Increase, Reduce, Close, Reverse), calculate PnL & fees, and return updated PortfolioState.
        [DEPENDENCIES]: Fill, Position, Account, calculate_realized_pnl.
        [ARGS]: fill — Trade Fill object generated by ExecutionEngine.
        [RETURNS]: Updated PortfolioState snapshot.
        [SIDE EFFECTS]: Mutates internal account, positions, and processed_fill_ids state.
        """
        # Invariant check: Duplicate Fill application
        if fill.fill_id in self.processed_fill_ids:
            return self.get_state(fill.timestamp)

        self.last_timestamp = fill.timestamp
        symbol = fill.symbol
        existing_pos = self.positions.get(symbol)
        realized_pnl_delta = 0.0

        # --- CASE 1: FLAT POSITION (NO POSITION EXISTENT) ---
        if existing_pos is None:
            side = PositionSide.LONG if fill.side == OrderSide.BUY else PositionSide.SHORT
            self.positions[symbol] = Position(
                symbol=symbol,
                side=side,
                quantity=fill.quantity,
                average_entry_price=fill.price,
                realized_pnl=0.0,
                unrealized_pnl=0.0,
            )

        # --- CASE 2: EXISTING LONG POSITION ---
        elif existing_pos.side == PositionSide.LONG:
            if fill.side == OrderSide.BUY:
                # INCREASE LONG
                new_qty = existing_pos.quantity + fill.quantity
                new_entry = (existing_pos.quantity * existing_pos.average_entry_price + fill.quantity * fill.price) / new_qty
                self.positions[symbol] = Position(
                    symbol=symbol,
                    side=PositionSide.LONG,
                    quantity=new_qty,
                    average_entry_price=new_entry,
                    realized_pnl=existing_pos.realized_pnl,
                    unrealized_pnl=existing_pos.unrealized_pnl,
                )
            elif fill.side == OrderSide.SELL:
                if fill.quantity <= existing_pos.quantity:
                    # REDUCE / CLOSE LONG
                    closed_qty = fill.quantity
                    realized_pnl_delta = calculate_realized_pnl(PositionSide.LONG, existing_pos.average_entry_price, fill.price, closed_qty)
                    rem_qty = existing_pos.quantity - fill.quantity

                    if rem_qty == 0.0:
                        # Full Close
                        self.positions.pop(symbol, None)
                    else:
                        # Partial Reduce
                        self.positions[symbol] = Position(
                            symbol=symbol,
                            side=PositionSide.LONG,
                            quantity=rem_qty,
                            average_entry_price=existing_pos.average_entry_price,
                            realized_pnl=existing_pos.realized_pnl + realized_pnl_delta,
                            unrealized_pnl=existing_pos.unrealized_pnl,
                        )
                else:
                    # REVERSAL: LONG -> SHORT
                    # Step 1: Close Long
                    realized_pnl_delta = calculate_realized_pnl(PositionSide.LONG, existing_pos.average_entry_price, fill.price, existing_pos.quantity)
                    # Step 2: Open Short with remaining fill quantity
                    short_qty = fill.quantity - existing_pos.quantity
                    self.positions[symbol] = Position(
                        symbol=symbol,
                        side=PositionSide.SHORT,
                        quantity=short_qty,
                        average_entry_price=fill.price,
                        realized_pnl=0.0,
                        unrealized_pnl=0.0,
                    )

        # --- CASE 3: EXISTING SHORT POSITION ---
        elif existing_pos.side == PositionSide.SHORT:
            if fill.side == OrderSide.SELL:
                # INCREASE SHORT
                new_qty = existing_pos.quantity + fill.quantity
                new_entry = (existing_pos.quantity * existing_pos.average_entry_price + fill.quantity * fill.price) / new_qty
                self.positions[symbol] = Position(
                    symbol=symbol,
                    side=PositionSide.SHORT,
                    quantity=new_qty,
                    average_entry_price=new_entry,
                    realized_pnl=existing_pos.realized_pnl,
                    unrealized_pnl=existing_pos.unrealized_pnl,
                )
            elif fill.side == OrderSide.BUY:
                if fill.quantity <= existing_pos.quantity:
                    # REDUCE / CLOSE SHORT
                    closed_qty = fill.quantity
                    realized_pnl_delta = calculate_realized_pnl(PositionSide.SHORT, existing_pos.average_entry_price, fill.price, closed_qty)
                    rem_qty = existing_pos.quantity - fill.quantity

                    if rem_qty == 0.0:
                        # Full Close
                        self.positions.pop(symbol, None)
                    else:
                        # Partial Reduce
                        self.positions[symbol] = Position(
                            symbol=symbol,
                            side=PositionSide.SHORT,
                            quantity=rem_qty,
                            average_entry_price=existing_pos.average_entry_price,
                            realized_pnl=existing_pos.realized_pnl + realized_pnl_delta,
                            unrealized_pnl=existing_pos.unrealized_pnl,
                        )
                else:
                    # REVERSAL: SHORT -> LONG
                    # Step 1: Close Short
                    realized_pnl_delta = calculate_realized_pnl(PositionSide.SHORT, existing_pos.average_entry_price, fill.price, existing_pos.quantity)
                    # Step 2: Open Long with remaining fill quantity
                    long_qty = fill.quantity - existing_pos.quantity
                    self.positions[symbol] = Position(
                        symbol=symbol,
                        side=PositionSide.LONG,
                        quantity=long_qty,
                        average_entry_price=fill.price,
                        realized_pnl=0.0,
                        unrealized_pnl=0.0,
                    )

        # Update Account financial state
        self.account = self.account.apply_transaction(
            realized_pnl_delta=realized_pnl_delta,
            fee_delta=fill.fee,
            funding_delta=0.0
        )

        self.processed_fill_ids.add(fill.fill_id)
        return self.get_state(fill.timestamp)

    def mark_to_market(self, symbol: str, mark_price: float, timestamp: datetime) -> PortfolioState:
        """
        [PURPOSE]: Update mark-to-market unrealized PnL for a symbol and return updated PortfolioState snapshot.
        [DEPENDENCIES]: calculate_unrealized_pnl, Position.
        [ARGS]:
            symbol — Instrument symbol.
            mark_price — Current mark price.
            timestamp — Current evaluation timestamp.
        [RETURNS]: PortfolioState snapshot.
        """
        self.last_timestamp = timestamp
        pos = self.positions.get(symbol)
        if pos is not None:
            unrealized = calculate_unrealized_pnl(pos.side, pos.average_entry_price, mark_price, pos.quantity)
            self.positions[symbol] = pos.with_unrealized_pnl(unrealized)

        return self.get_state(timestamp)

    def get_position(self, symbol: str) -> Optional[Position]:
        """
        [PURPOSE]: Get open position for symbol, or None if flat.
        [RETURNS]: Optional Position.
        """
        return self.positions.get(symbol)

    def get_state(self, timestamp: Optional[datetime] = None) -> PortfolioState:
        """
        [PURPOSE]: Compute and return an immutable PortfolioState snapshot.
        [DEPENDENCIES]: Account, MarginModel, PortfolioState.
        """
        ts = timestamp or self.last_timestamp or datetime.now(timezone.utc)
        total_unrealized = sum(pos.unrealized_pnl for pos in self.positions.values())
        equity = self.account.compute_equity(total_unrealized)

        used_margin = 0.0
        for pos in self.positions.values():
            notional = pos.notional(pos.average_entry_price)
            used_margin += self.margin_model.calculate_initial_margin(notional, self.leverage)

        available_margin = max(0.0, equity - used_margin)

        return PortfolioState(
            timestamp=ts,
            balance=self.account.balance,
            equity=equity,
            realized_pnl=self.account.realized_pnl,
            unrealized_pnl=total_unrealized,
            fees_paid=self.account.fees_paid,
            funding_paid=self.account.funding_paid,
            used_margin=used_margin,
            available_margin=available_margin,
            positions={k: v for k, v in self.positions.items()}
        )
