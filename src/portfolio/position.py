"""
[PURPOSE]: Define PositionSide enum and immutable Position dataclass representing market exposure.
[DEPENDENCIES]: enum, dataclasses, src.portfolio.exceptions.
"""

from enum import Enum
from dataclasses import dataclass
from src.portfolio.exceptions import InvalidPositionError

class PositionSide(Enum):
    LONG = "LONG"
    SHORT = "SHORT"

@dataclass(frozen=True)
class Position:
    """
    [PURPOSE]: Immutable dataclass representing open position exposure for a single symbol.
    [DEPENDENCIES]: PositionSide, InvalidPositionError.
    [ARGS]:
        symbol — Instrument symbol (e.g. 'BTCUSDT').
        side — PositionSide (LONG or SHORT).
        quantity — Position size quantity (MUST be > 0 always!).
        average_entry_price — Weighted average entry price (> 0).
        realized_pnl — Cumulative realized PnL generated by this position.
        unrealized_pnl — Current mark-to-market unrealized PnL.
    [RETURNS]: Position instance.
    [SIDE EFFECTS]: Raises InvalidPositionError if invariants are violated (e.g. qty <= 0 or entry <= 0).
    """
    symbol: str
    side: PositionSide
    quantity: float
    average_entry_price: float
    realized_pnl: float = 0.0
    unrealized_pnl: float = 0.0

    def __post_init__(self) -> None:
        if self.quantity <= 0:
            raise InvalidPositionError(f"Position quantity must be strictly positive (> 0), got {self.quantity}.")
        if self.average_entry_price <= 0:
            raise InvalidPositionError(f"Average entry price must be positive, got {self.average_entry_price}.")

    def notional(self, mark_price: float) -> float:
        """
        [PURPOSE]: Calculate position notional value = quantity * mark_price.
        [ARGS]: mark_price — Current market/mark price (> 0).
        [RETURNS]: Float notional value.
        """
        if mark_price <= 0:
            raise InvalidPositionError(f"Mark price must be positive, got {mark_price}.")
        return self.quantity * mark_price

    def with_unrealized_pnl(self, unrealized_pnl: float) -> "Position":
        """
        [PURPOSE]: Create updated Position copy with new unrealized PnL.
        [RETURNS]: New Position instance.
        """
        return Position(
            symbol=self.symbol,
            side=self.side,
            quantity=self.quantity,
            average_entry_price=self.average_entry_price,
            realized_pnl=self.realized_pnl,
            unrealized_pnl=unrealized_pnl,
        )
