"""
[PURPOSE]: Core implementation of Phase 1 Basic Metrics evaluation package.
[DEPENDENCIES]: Consumes src.backtest.result.BacktestResult; raises src.evaluation.exceptions.InvalidEvaluationError.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Tuple

from src.engine.backtest.backtest_result import BacktestResult
from src.evaluation.exceptions import InvalidEvaluationError


@dataclass(frozen=True)
class BasicMetrics:
    """
    [PURPOSE]: Read-only container representing basic performance metrics of a completed backtest.
    [DEPENDENCIES]: Generated by calculate_basic_metrics() or BasicMetrics.from_result().
    [ARGS]:
        initial_capital — Starting account cash balance.
        final_equity — Portfolio total equity at backtest completion.
        net_pnl — Net profit or loss (final_equity - initial_capital).
        return_pct — Total percentage return on initial capital.
        realized_pnl — Total closed trade realized profit/loss.
        total_fees — Cumulative execution commissions and fees.
        trade_count — Number of completed trade realizations.
        win_rate — Percentage of completed trades with positive realized PnL.
        equity_curve — Immutable sequence of (timestamp, equity) tuples.
    [RETURNS]: None.
    [SIDE EFFECTS]: None (immutable dataclass).
    """
    initial_capital: float
    final_equity: float
    net_pnl: float
    return_pct: float
    realized_pnl: float
    total_fees: float
    trade_count: int
    win_rate: float
    equity_curve: Tuple[Tuple[datetime, float], ...]

    @classmethod
    def from_result(cls, result: BacktestResult) -> "BasicMetrics":
        """
        [PURPOSE]: Factory method constructing BasicMetrics directly from a BacktestResult.
        [DEPENDENCIES]: Calls calculate_basic_metrics().
        [ARGS]: result — Completed BacktestResult instance.
        [RETURNS]: BasicMetrics immutable instance.
        [SIDE EFFECTS]: None.
        """
        return calculate_basic_metrics(result)


def calculate_basic_metrics(result: BacktestResult) -> BasicMetrics:
    """
    [PURPOSE]: Compute Phase 1 basic performance metrics from a completed BacktestResult.
    [DEPENDENCIES]: Called by BasicMetrics.from_result() or evaluation pipeline.
    [ARGS]: result — Completed BacktestResult instance.
    [RETURNS]: BasicMetrics instance containing computed statistics.
    [SIDE EFFECTS]: None (pure calculation function).
    """
    if result.initial_capital <= 0.0:
        raise InvalidEvaluationError(
            f"Initial capital must be strictly positive (> 0), got: {result.initial_capital}"
        )

    initial_capital = float(result.initial_capital)
    final_equity = float(result.final_equity)
    net_pnl = final_equity - initial_capital
    return_pct = (net_pnl / initial_capital) * 100.0
    realized_pnl = float(result.realized_pnl)
    total_fees = float(result.total_fees)

    # Extract equity curve
    equity_curve = tuple(
        (snap.timestamp, float(snap.equity))
        for snap in result.portfolio_history
    )

    # Calculate trade count and win rate from realized PnL deltas across snapshot history
    winning_trades = 0
    trade_count = 0

    if len(result.portfolio_history) > 1:
        # Track realized PnL transitions between consecutive snapshots
        for i in range(1, len(result.portfolio_history)):
            prev_pnl = float(result.portfolio_history[i - 1].realized_pnl)
            curr_pnl = float(result.portfolio_history[i].realized_pnl)
            delta = curr_pnl - prev_pnl

            # A non-zero delta signifies a realized trade event (close or partial close)
            if abs(delta) > 1e-9:
                trade_count += 1
                if delta > 0.0:
                    winning_trades += 1

    win_rate = (winning_trades / trade_count * 100.0) if trade_count > 0 else 0.0

    return BasicMetrics(
        initial_capital=initial_capital,
        final_equity=final_equity,
        net_pnl=net_pnl,
        return_pct=return_pct,
        realized_pnl=realized_pnl,
        total_fees=total_fees,
        trade_count=trade_count,
        win_rate=win_rate,
        equity_curve=equity_curve,
    )
